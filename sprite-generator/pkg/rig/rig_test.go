// writeMiniRig builds a tiny rig from code so the test owns every pixel.
func writeMiniRig(t *testing.T) string {
	t.Helper()
	dir := t.TempDir()
	must := func(err error) {
		if err != nil {
			t.Fatal(err)
		}
	}
	must(os.WriteFile(filepath.Join(dir, "rig.yml"), []byte(miniRigYML), 0o644))
	must(os.WriteFile(filepath.Join(dir, "poses.yml"), []byte(miniPosesYML), 0o644))
	must(os.WriteFile(filepath.Join(dir, "clips.yml"), []byte(miniClipsYML), 0o644))

	outline, _ := ParseHex("#101010")
	skin0, _ := ParseHex("#c08060")
	skin1, _ := ParseHex("#e0a080")
	hair0, _ := ParseHex("#402010")
	hair1, _ := ParseHex("#603020")
	part := func(layer, variant, name string, draw func(img *image.NRGBA)) {
		img := image.NewNRGBA(image.Rect(0, 0, 16, 16))
		draw(img)
		p := filepath.Join(dir, "parts", layer, variant, name+".png")
		must(os.MkdirAll(filepath.Dir(p), 0o755))
		must(os.WriteFile(p, EncodePNG(img), 0o644))
	}
	part("body", "default", "stand", func(img *image.NRGBA) {
		for y := 4; y < 15; y++ {
			setRGB(img, 5, y, outline)
			setRGB(img, 10, y, outline)
			for x := 6; x < 10; x++ {
				setRGB(img, x, y, skin1)
			}
		}
		setRGB(img, 7, 8, skin0)
	})
	part("body", "default", "walk", func(img *image.NRGBA) {
		for y := 4; y < 15; y++ {
			for x := 6; x < 10; x++ {
				setRGB(img, x+(y%2), y, skin0)
			}
		}
	})
	part("hair", "short", "stand", func(img *image.NRGBA) {
		for x := 5; x < 11; x++ {
			setRGB(img, x, 2, hair1)
			setRGB(img, x, 3, hair0)
		}
	})
	part("hair", "long", "stand", func(img *image.NRGBA) {
		for y := 2; y < 9; y++ {
			setRGB(img, 5, y, hair0)
			setRGB(img, 10, y, hair0)
		}
		for x := 5; x < 11; x++ {
			setRGB(img, x, 2, hair1)
		}
	})
	return dir
}

func loadMini(t *testing.T) *Rig {
	t.Helper()
	r, err := Load(writeMiniRig(t))
	if err != nil {
		t.Fatal(err)
	}
	return r
}

func TestMiniRigValid(t *testing.T) {
	r := loadMini(t)
	if errs := r.Validate(); len(errs) > 0 {
		t.Fatalf("unexpected validation errors:\n%s", strings.Join(errs, "\n"))
	}
}

// TestBuildGolden pins every generated byte. Run with -update after an
// intentional format change.
func TestBuildGolden(t *testing.T) {
	r := loadMini(t)
	outs, err := r.Build()
	if err != nil {
		t.Fatal(err)
	}
	golden := filepath.Join("testdata", "golden")
	for _, o := range outs {
		rel, err := filepath.Rel(r.Dir, o.Path)
		if err != nil {
			t.Fatal(err)
		}
		want := filepath.Join(golden, rel)
		if *update {
			if err := os.MkdirAll(filepath.Dir(want), 0o755); err != nil {
				t.Fatal(err)
			}
			if err := os.WriteFile(want, o.Data, 0o644); err != nil {
				t.Fatal(err)
			}
			continue
		}
		data, err := os.ReadFile(want)
		if err != nil {
			t.Fatalf("missing golden %s (run go test ./... -update): %v", want, err)
		}
		if !bytes.Equal(data, o.Data) {
			t.Errorf("%s differs from golden %s", rel, want)
		}
	}
}

func TestBuildDeterministic(t *testing.T) {
	r := loadMini(t)
	a, err := r.Build()
	if err != nil {
		t.Fatal(err)
	}
	b, err := r.Build()
	if err != nil {
		t.Fatal(err)
	}
	if len(a) != len(b) {
		t.Fatalf("output count changed: %d vs %d", len(a), len(b))
	}
	for i := range a {
		if a[i].Path != b[i].Path || !bytes.Equal(a[i].Data, b[i].Data) {
			t.Errorf("%s not deterministic", a[i].Path)
		}
	}
}

func TestStaleDetection(t *testing.T) {
	r := loadMini(t)
	outs, err := r.Build()
	if err != nil {
		t.Fatal(err)
	}
	if got := len(Stale(outs)); got != len(outs) {
		t.Fatalf("before writing, want all %d stale, got %d", len(outs), got)
	}
	for _, o := range outs {
		_ = os.MkdirAll(filepath.Dir(o.Path), 0o755)
		if err := os.WriteFile(o.Path, o.Data, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	if s := Stale(outs); len(s) != 0 {
		t.Fatalf("after writing, want none stale, got %v", s)
	}
}

func TestOffsetsAndRecolour(t *testing.T) {
	r := loadMini(t)
	img, err := r.Compose(map[string]string{"hair": "short"}, map[string]string{"skin": "light", "hair": "blonde"})
	if err != nil {
		t.Fatal(err)
	}
	// Pose 1 (breathe) is at column 1: hair row 2 moves to row 3.
	blonde1, _ := ParseHex("#e0c060")
	if c, _ := rgbAt(img, 16+6, 3); c != blonde1 {
		t.Errorf("breathe hair offset/recolour: got %s want %s", c.Hex(), blonde1.Hex())
	}
	if _, ok := rgbAt(img, 16+6, 2); ok {
		t.Errorf("breathe pose row 2 should be empty after dy=1 offset")
	}
	// Fixed outline colour is never recoloured.
	if c, _ := rgbAt(img, 5, 6); c.Hex() != "#101010" {
		t.Errorf("outline recoloured to %s", c.Hex())
	}
}

func TestValidateCatchesMistakes(t *testing.T) {
	cases := []struct {
		name   string
		mutate func(r *Rig)
		want   string
	}{
		{"unknown pose in clip", func(r *Rig) { r.Clips.Clips["idle"][0].Pose = "nope" }, `unknown pose "nope"`},
		{"zero weight", func(r *Rig) { r.Clips.Idle.Variants[0].Weight = 0 }, "weight must be > 0"},
		{"offset out of frame", func(r *Rig) { r.Poses[1].Offsets["hair"] = [2]int{0, -5} }, "out of frame"},
		{"palette wrong length", func(r *Rig) { r.Spec.Palettes["hair"]["red"] = []string{"#ff0000"} }, "palette hair.red has 1 colours"},
		{"missing variant part", func(r *Rig) { r.Poses[2].Parts["hair"] = "walk" }, "missing part walk"},
		{"hand outside frame", func(r *Rig) { r.Poses[0].Hand = &[2]int{16, 0} }, "hand"},
		{"duplicate key colour", func(r *Rig) { r.Spec.Fixed = append(r.Spec.Fixed, "#c08060") }, "used by both"},
		{"bad default palette", func(r *Rig) { r.Spec.Defaults.Palettes["hair"] = "green" }, `defaults.palettes.hair = "green"`},
		{"hitbox outside frame", func(r *Rig) { r.Spec.Hitbox = &[4]int{10, 0, 8, 16} }, "hitbox [10 0 8 16] must have positive size"},
		{"hitbox empty", func(r *Rig) { r.Spec.Hitbox = &[4]int{0, 0, 0, 16} }, "hitbox"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			r := loadMini(t)
			tc.mutate(r)
			errs := strings.Join(r.Validate(), "\n")
			if !strings.Contains(errs, tc.want) {
				t.Fatalf("want error containing %q, got:\n%s", tc.want, errs)
			}
		})
	}
}

func TestValidateRejectsStrayColour(t *testing.T) {
	r := loadMini(t)
	p := r.PartPath("body", "default", "walk")
	img, err := ReadPNG(p)
	if err != nil {
		t.Fatal(err)
	}
	setRGB(img, 0, 0, RGB{1, 2, 3})
	if err := os.WriteFile(p, EncodePNG(img), 0o644); err != nil {
		t.Fatal(err)
	}
	errs := strings.Join(r.Validate(), "\n")
	if !strings.Contains(errs, "#010203 is not a rig colour") {
		t.Fatalf("stray colour not reported:\n%s", errs)
	}
}

