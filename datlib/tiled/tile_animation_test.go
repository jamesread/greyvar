func TestSanitizeAnimations(t *testing.T) {
	got := SanitizeAnimations(map[int][]AnimFrame{
		1: {{TileID: 1, DurationMs: 200}, {TileID: 2, DurationMs: 0}, {TileID: 99, DurationMs: 100}},
		5: {{TileID: 5, DurationMs: 100}, {TileID: 50, DurationMs: 100}}, // one valid frame left
	}, 10)
	if len(got) != 1 {
		t.Fatalf("want only tile 1 kept, got %v", got)
	}
	f := got[1]
	if len(f) != 2 || f[1].DurationMs != DefaultAnimFrameMs {
		t.Fatalf("want out-of-range frame dropped and default duration, got %v", f)
	}
	if SanitizeAnimations(map[int][]AnimFrame{}, 4) != nil {
		t.Fatal("empty input should give nil")
	}
}

// The real grass tileset animates tiles 115 and 121 (ripples).
func TestGrassTilesetAnimations(t *testing.T) {
	cat, _, err := LoadTilesetFile(filepath.Join("..", "..", "res", "img", "textures", "tilesets", "grass_terrains.tsx"))
	if err != nil {
		t.Fatal(err)
	}
	atlases := cat.AtlasTilesets()
	if len(atlases) != 1 {
		t.Fatalf("want 1 atlas, got %d", len(atlases))
	}
	anims := atlases[0].Animations
	for _, id := range []int{115, 121} {
		if len(anims[id]) != 6 {
			t.Errorf("tile %d: want 6 frames, got %v", id, anims[id])
		}
	}
	if anims[115][1].TileID != 116 || anims[115][1].DurationMs != 200 {
		t.Errorf("tile 115 frame 1 = %+v", anims[115][1])
	}
}

func TestEmbeddedTilesetAnimations(t *testing.T) {
	raw := json.RawMessage(`[{"firstgid":1,"name":"emb","image":"/x/res/img/textures/tilesets/emb.png",
	  "tilewidth":16,"tileheight":16,"columns":4,"tilecount":8,
	  "tiles":[{"id":2,"animation":[{"tileid":2,"duration":150},{"tileid":3,"duration":150},{"tileid":30,"duration":150}]}]}]`)
	refs, err := ParseTilesetRefs(raw)
	if err != nil {
		t.Fatal(err)
	}
	cat, err := LoadTilesetsFromMap(t.TempDir(), refs)
	if err != nil {
		t.Fatal(err)
	}
	atlases := cat.AtlasTilesets()
	if len(atlases) != 1 {
		t.Fatalf("want 1 atlas, got %d", len(atlases))
	}
	if f := atlases[0].Animations[2]; len(f) != 2 || f[1].TileID != 3 {
		t.Fatalf("want 2 in-range frames for tile 2, got %v", f)
	}
}

// flora.tsx is generated by sprite-generator (res/sprites/flora): every flower
// tile must load as an animation.
func TestFloraTilesetAnimations(t *testing.T) {
	cat, _, err := LoadTilesetFile(filepath.Join("..", "..", "res", "img", "textures", "tilesets", "flora.tsx"))
	if err != nil {
		t.Fatal(err)
	}
	anims := cat.AtlasTilesets()[0].Animations
	if len(anims) != 3 {
		t.Fatalf("want 3 animated flora tiles, got %d", len(anims))
	}
	for id, frames := range anims {
		if len(frames) != 4 || frames[0].TileID != id {
			t.Errorf("tile %d: want 4 frames starting on itself, got %v", id, frames)
		}
	}
}

// Water (res/sprites/water/tileanim.yml): sand shorelines animate a
// PixelLab tide, all in sync; open water and plain sand stay still.
func TestShoreTilesAnimateSynced(t *testing.T) {
	cat, _, err := LoadTilesetFile(filepath.Join("..", "..", "res", "img", "textures", "tilesets", "grass_terrains.tsx"))
	if err != nil {
		t.Fatal(err)
	}
	a := cat.AtlasTilesets()[0]
	// Opaque water/sand (hand-made maps) and see-through sand edges (generated maps).
	for _, id := range []int{132, 133, 152, 174, 4, 43, 44, 85} {
		if len(a.Animations[id]) != 8 || !a.Synced[id] {
			t.Errorf("shore tile %d: want 8 synced frames, got %d synced=%v", id, len(a.Animations[id]), a.Synced[id])
		}
	}
	for _, id := range []int{153, 64} {
		if len(a.Animations[id]) != 0 {
			t.Errorf("tile %d (open water / plain sand) should not animate", id)
		}
	}
}
